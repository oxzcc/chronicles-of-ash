/** Запись истории для промпта. */
export type HistoryEntry =
  | { who: "player"; text: string }
  | { who: "gm"; text: string; speaker?: string; line?: string }
  | { who: "roll" | "combat" | "system"; text: string };

export function historyText(entries: HistoryEntry[], limit = 14): string {
  return entries
    .slice(-limit)
    .map((e) => {
      if (e.who === "player") return `Игрок: ${e.text}`;
      if (e.who === "gm") return `Мастер: ${e.text}${e.line ? `\n${e.speaker || "NPC"}: «${e.line}»` : ""}`;
      if (e.who === "roll") return `[Бросок] ${e.text}`;
      if (e.who === "combat") return `[Бой] ${e.text}`;
      return `[${e.text}]`;
    })
    .join("\n");
}

/** Версия промптов мира для журнала ходов: у фэнтези — просто PROMPT_VERSION. */
export const promptVersion = (world: World) => (world.gm.version ? `${PROMPT_VERSION}+${world.gm.version}` : PROMPT_VERSION);

/** Неизменная часть — кэшируется провайдером. Описание мира пока целиком; поиск фрагментов — позже в фазе 1. */
export function narratorSystemPrompt(world: World, worldBible: string): string {
  const rules = gmRules(world);
  return worldBible.trim() ? `${rules}\n\nОПИСАНИЕ МИРА\n${worldBible.trim()}` : rules;
}

export interface SceneContext {
  character: Character;
  campaign: Campaign;
  history: HistoryEntry[];
  action: string;
}

/** Меняющаяся часть: герой, квест, место, летопись, последние события, ход. */
export function narratorUserPrompt(world: World, { character, campaign: w, history, action }: SceneContext): string {
  const R = world.rules;
  const cur = locationById(w, w.current)!;
  // В деле герой ходит по известным адресам, а не по дорогам.
  // Визиты по делу кончились — идти некуда, пора закрывать дело.
  const timeUp = !!w.case && w.case.visits >= w.case.limit;
  const nb = (w.case ? w.locations.filter((l) => !timeUp && w.case!.known.includes(l.id) && l.id !== w.current) : neighbors(w, w.current))
    .map((l) => `${l.name} (${locationTypeName(R, l.type)})`)
    .join("; ");
  const objs = w.objectives.map((o) => `[${o.id}] ${o.text} — ${o.done ? "выполнено" : "не выполнено"}`).join("\n");
  return `ГЕРОЙ
${sheetText(R, character)}

КВЕСТ: «${w.questTitle}». ${w.hook}
Цели:
${objs}${w.complete ? "\nКвест уже завершён: веди эпилог или новую нить истории." : ""}

ТЕКУЩАЯ ЛОКАЦИЯ: ${cur.name} (${locationTypeName(R, cur.type)}) — ${cur.desc}
Куда можно пойти (${w.case ? "известные герою адреса, каждый переход — визит по делу" : "соседние места на карте"}): ${nb || (timeUp ? "никуда — визиты кончились" : "никуда")}${w.case ? `\n\n${caseScene(world, w)}` : ""}
${w.npc ? `Сейчас рядом: ${w.npc.name} (${w.npc.role})` : ""}

ЛЕТОПИСЬ (сжатое прошлое): ${w.summary || "приключение только началось"}

ПОСЛЕДНИЕ СОБЫТИЯ:
${historyText(history) || "—"}

ХОД ИГРОКА: ${action}`;
}

